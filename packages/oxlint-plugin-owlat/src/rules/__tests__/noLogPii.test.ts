import rule from '../noLogPii.ts';
import { ruleTester } from '../../__tests__/ruleTester.ts';

const filename = '/repo/apps/api/convex/inbound/log.ts';
const options = [{ files: ['apps/api/convex/**'] }];
const reported = (key: string) => ({ message: new RegExp(`^\`${key}\` puts a correspondent`) });

ruleTester.run('owlat/no-log-pii', rule, {
	valid: [
		{
			name: 'values passed through the redaction helpers',
			filename,
			options,
			code: [
				"logWarn('[Inbound Email] duplicate delivery', {",
				'\tmessageId: args.messageId,',
				'\tfrom: redactEmailAddress(args.from),',
				'\tto: args.to.map(redactEmailAddress),',
				'\tsubject: redactSubject(args.subject),',
				'\tsender: redactionDigest(args.sender),',
				'\trecipient: redactEmailAddresses([args.recipient]),',
				'});',
			].join('\n'),
		},
		{
			name: 'redactors under an alias, through a namespace or a local alias',
			filename,
			options,
			code: [
				"import { redactEmailAddress as redact } from '@owlat/shared/logRedaction';",
				"import * as redaction from '@owlat/shared/logRedaction';",
				'const digest = redaction.redactionDigest;',
				"logInfo('sent', {",
				'\tto: redact(args.to),',
				'\tsubject: redaction.redactSubject(args.subject),',
				'\tsender: digest(args.sender),',
				'\trecipient: args.recipients.map(redact),',
				'});',
			].join('\n'),
		},
		{
			name: 'every outcome of the value redacted or absent',
			filename,
			options,
			code: [
				"logInfo('sent', {",
				'\tto: hide ? redactEmailAddress(args.to) : undefined,',
				'\tfrom: args.from && redactEmailAddress(args.from),',
				'\tsubject: (args.subject ? redactSubject(args.subject) : null) ?? redactSubject(fallback),',
				"\trcptTo: redactEmailAddresses(args.rcptTo).join(', '),",
				'\trecipient: args.recipients.map((r) => redactEmailAddress(r.address)),',
				'\tsender: `${redactEmailAddress(a)} via ${redactEmailAddress(b)}`,',
				'\taddress: [redactEmailAddress(a), redactEmailAddress(b)],',
				'\temail: args.email ? redactEmailAddress(args.email) : null,',
				'});',
			].join('\n'),
		},
		{
			name: 'a logEvent whose detail is redacted or carries only qualified names',
			filename,
			options,
			code: [
				"import { logEvent } from '../lib/runtimeLog';",
				"import { logEvent as emit } from '../lib/runtimeLog';",
				"import * as runtimeLog from '../lib/runtimeLog';",
				"logEvent('inbound.duplicate', {",
				'\tmessageId: args.messageId,',
				'\tdetail: {',
				'\t\tfrom: redactEmailAddress(args.from),',
				'\t\tsubject: redactSubject(args.subject),',
				'\t\tfromDomain: domainOf(args.from),',
				'\t},',
				"}, 'warn');",
				"emit('inbound.duplicate', { detail: { to: redactEmailAddresses(args.to) } }, 'warn');",
				"runtimeLog.logEvent('inbound.duplicate', { detail: { sender: redactionDigest(s) } });",
				"logEventRecord('inbound.duplicate', 'warn', { detail: { from: args.from } });",
			].join('\n'),
		},
		{
			name: 'qualified names: a domain, a count, an id or a digest',
			filename,
			options,
			code: "logInfo('delivered', { fromDomain: d, toCount: 3, senderId: id, recipientHash: h, addressCount: 3 });",
		},
		{
			name: 'an inline log-pii-safe justification',
			filename,
			options,
			code: [
				"logInfo('webhook received', {",
				'\t// log-pii-safe: the provider routing label, not a mailbox',
				'\tfrom: payload.queueName,',
				'});',
			].join('\n'),
		},
		{
			name: 'a justification in the comment lines directly above',
			filename,
			options,
			code: [
				'// The header names are constants.',
				'// log-pii-safe: header NAMES, never their values',
				"logInfo('headers dropped', { from: HEADER_FROM, subject: HEADER_SUBJECT });",
			].join('\n'),
		},
		{
			name: 'object keys outside a log call',
			filename,
			options,
			code: "await ctx.runMutation(internal.inbox.transition, { inboundMessageId, to: 'archived', from: args.from });",
		},
		{
			name: 'an unrelated console-like object',
			filename,
			options,
			code: "logger.warn('x', { from: args.from });",
		},
		{
			name: 'an unrelated console method',
			filename,
			options,
			code: 'console.table({ from: args.from });',
		},
		{
			name: 'a method named like a console method from another module',
			filename,
			options,
			code: [
				"import { warn } from './sink';",
				"import * as sink from './sink';",
				"warn('x', { to: args.to });",
				"sink.error('x', { from: args.from });",
			].join('\n'),
		},
		{
			name: 'a computed call',
			filename,
			options,
			code: "loggers['logInfo' + suffix]('x', { from: args.from });",
		},
		{
			name: 'test files',
			filename: '/repo/apps/api/convex/inbound/log.test.ts',
			options,
			code: "logInfo('x', { from: args.from });",
		},
		{
			name: 'a file without log calls',
			filename,
			options,
			code: 'export const envelope = { from: args.from };',
		},
		{
			name: 'a destructured callback parameter named like an address field',
			filename,
			options,
			code: [
				"logInfo('mapped', {",
				'\tto: recipients.map(({ email }) => redactEmailAddress(email)),',
				'\tfrom: senders.map(({ address: from = fallback }) => redactEmailAddress(from)),',
				'});',
			].join('\n'),
		},
	],
	invalid: [
		{
			name: 'a multi-line payload carrying from / to / subject',
			filename,
			options,
			code: [
				"logWarn('[Inbound Email] duplicate delivery', {",
				'\tmessageId: args.messageId,',
				'\tfrom: args.from,',
				'\tto: args.to,',
				'\tsubject: args.subject,',
				'});',
			].join('\n'),
			errors: [reported('from'), reported('to'), reported('subject')],
		},
		{
			name: 'raw console calls and member log helpers',
			filename,
			options,
			code: "console.warn('bounced', { rcptTo: job.rcptTo });\nruntime.logError('x', { mailFrom: m });",
			errors: [reported('rcptTo'), reported('mailFrom')],
		},
		{
			name: 'shorthand and quoted keys',
			filename,
			options,
			code: "logInfo('sent', { email, 'address': addr, ['sender']: s });",
			errors: [reported('email'), reported('address'), reported('sender')],
		},
		{
			name: 'a raw address beside a separately redacted subject on one line',
			filename,
			options,
			code: "logInfo('sent', { to: args.to, subject: redactSubject(args.subject) });",
			errors: [reported('to')],
		},
		{
			name: 'a key nested in the payload',
			filename,
			options,
			code: "logDebug('x', { envelope: { from: args.from } }, [{ recipient: r }]);",
			errors: [reported('from'), reported('recipient')],
		},
		{
			name: 'a call longer than any line cap',
			filename,
			options,
			code: `logInfo('long', {\n${Array.from({ length: 30 }, (_, i) => `\tfield${i}: ${i},`).join('\n')}\n\tto: args.to,\n});`,
			errors: [reported('to')],
		},
		{
			name: 'a justification does not leak onto a later call',
			filename,
			options,
			code: [
				'// log-pii-safe: this one is a label',
				"logInfo('a', { from: label });",
				'',
				'const x = 1;',
				'',
				"logInfo('b', { from: args.from });",
			].join('\n'),
			errors: [reported('from')],
		},
		{
			name: 'an empty justification does not count',
			filename,
			options,
			code: "// log-pii-safe:\nlogInfo('a', { from: args.from });",
			errors: [reported('from')],
		},
		{
			name: 'a payload built in a callback',
			filename,
			options,
			code: "logInfo('mapped', { recipients: items.map((item) => ({ to: item.to })) });",
			errors: [reported('to')],
		},
		{
			name: 'a destructured parameter logged raw from the callback body',
			filename,
			options,
			code: "logInfo('mapped', { recipients: items.map(({ email }) => ({ email })) });",
			errors: [reported('email')],
		},
		{
			name: 'a value where a redactor appears but some outcome stays raw',
			filename,
			options,
			code: [
				"logInfo('sent', {",
				'\tto: redact ? redactEmailAddress(args.to) : args.to,',
				'\tfrom: redactEmailAddress(args.from) || args.from,',
				'\tsubject: describe(redactSubject, args.subject),',
				'\trcptTo: redactEmailAddress(a).concat(args.rcptTo),',
				'\trecipient: args.recipients.map((r) => r.address ?? redactEmailAddress(r.fallback)),',
				'\tsender: `${redactEmailAddress(a)} for ${args.sender}`,',
				'\taddress: [redactEmailAddress(a), args.address],',
				'\temail: redactEmailAddresses(list).join(args.email),',
				'});',
			].join('\n'),
			errors: ['to', 'from', 'subject', 'rcptTo', 'recipient', 'sender', 'address', 'email'].map(
				reported
			),
		},
		{
			name: 'console methods through a namespace import spelled console',
			filename,
			options,
			code: [
				"import * as console from 'node:console';",
				"console.warn('sent', { to: address });",
			].join('\n'),
			errors: [reported('to')],
		},
		{
			name: 'console methods imported from the console module',
			filename,
			options,
			code: [
				"import { warn as w, error } from 'node:console';",
				"import * as out from 'node:console';",
				"import stdout from 'console';",
				'const { log } = out;',
				'const { info } = globalThis.console;',
				'const alias = stdout;',
				"w('sent', { to: address });",
				"error('failed', { from: address });",
				"out.debug('trace', { subject: s });",
				"stdout.info('sent', { sender: s });",
				"log('sent', { recipient: r });",
				"info('sent', { email: e });",
				"globalThis.console.error('x', { rcptTo: r });",
				"alias.warn('x', { mailFrom: m });",
			].join('\n'),
			errors: ['to', 'from', 'subject', 'sender', 'recipient', 'email', 'rcptTo', 'mailFrom'].map(
				reported
			),
		},
		{
			name: 'template literals without a redacted hole',
			filename,
			options,
			code: [
				"logInfo('sent', {",
				'\tto: `ops@example.com`,',
				'\tfrom: `${args.from}`,',
				'});',
			].join('\n'),
			errors: [reported('to'), reported('from')],
		},
		{
			name: 'log helpers under an import alias, a namespace or a local alias',
			filename,
			options,
			code: [
				"import { logInfo as info } from '../lib/logging';",
				"import * as logging from '../lib/logging';",
				'const warn = logging.logWarn;',
				'const { error } = console;',
				'const debug = console.debug;',
				"info('sent', { to });",
				"logging.logError('failed', { from });",
				"warn('slow', { subject });",
				"error('bounced', { rcptTo });",
				"debug('trace', { sender });",
			].join('\n'),
			errors: [
				reported('to'),
				reported('from'),
				reported('subject'),
				reported('rcptTo'),
				reported('sender'),
			],
		},
		{
			name: 'a logEvent whose detail carries a raw address or subject',
			filename,
			options,
			code: [
				"logEvent('inbound.duplicate', {",
				'\tmessageId: args.messageId,',
				'\tdetail: { from: args.from, subject: args.subject },',
				"}, 'warn');",
			].join('\n'),
			errors: [reported('from'), reported('subject')],
		},
		{
			name: 'logEvent under an import alias, a namespace or a local alias',
			filename,
			options,
			code: [
				"import { logEvent as emit } from '../lib/runtimeLog';",
				"import * as runtimeLog from '../lib/runtimeLog';",
				'const event = runtimeLog.logEvent;',
				'const { logEvent: record } = runtimeLog;',
				"emit('inbound.duplicate', { detail: { from: args.from } }, 'warn');",
				"runtimeLog.logEvent('inbound.duplicate', { detail: { to: args.to } });",
				"event('inbound.duplicate', { detail: { subject: args.subject } });",
				"record('inbound.duplicate', { detail: { rcptTo: args.rcptTo } });",
			].join('\n'),
			errors: [reported('from'), reported('to'), reported('subject'), reported('rcptTo')],
		},
		{
			name: 'shapes the redaction check does not follow',
			filename,
			options,
			code: [
				"import * as redaction from '@owlat/shared/logRedaction';",
				'const { redactEmailAddress: local, ...others } = redaction;',
				'const { [name]: picked } = redaction;',
				"logInfo('sent', {",
				'\tto: list.map(function (a) { return redactEmailAddress(a); }),',
				'\tfrom: list.map(redactEmailAddress, thisArg),',
				'\tsubject: others.redactSubject(args.subject),',
				'\tsender: picked(args.sender),',
				'\trecipient: [...args.recipients.map(redactEmailAddress)],',
				"\taddress: 'ops@example.com',",
				'\trcptTo: local(args.rcptTo),',
				'});',
			].join('\n'),
			errors: ['to', 'from', 'subject', 'sender', 'recipient', 'address'].map(reported),
		},
		{
			name: 'a value redacted by a helper that only shares the name of a redactor',
			filename,
			options,
			code: "logInfo('sent', { to: util.redactEmailAddress(args.to) });",
			errors: [reported('to')],
		},
		{
			name: 'a nested log call is reported once',
			filename,
			options,
			code: "logInfo('outer', logWarn('inner', { to: args.to }));",
			errors: [reported('to')],
		},
	],
});
