import rule from '../requireSuppressionReason.ts';
import { ruleTester } from '../../__tests__/ruleTester.ts';

const LINT = /end the directive with `-- reason`/;
const TS = /write the reason after it/;

ruleTester.run('owlat/require-suppression-reason', rule, {
	valid: [
		{
			name: 'a lint directive with a -- reason',
			code: '// oxlint-disable-next-line no-control-regex -- strips C0 controls\nconst re = /\\x1b/;',
		},
		{
			name: 'an eslint-style file directive with a reason',
			code: '/* eslint-disable no-console -- this CLI reports to the terminal */\nconsole.log(1);',
		},
		{
			name: 'a directive explained by the comment on the line above',
			code: '// ANSI escapes start with ESC.\n// oxlint-disable-next-line no-control-regex\nconst re = /\\x1b/;',
		},
		{
			name: 'stacked directives under one explanation, with an empty comment line between',
			code: '// The fixture is wrong on purpose.\n//\n// @ts-expect-error\n// oxlint-disable-next-line no-unused-vars\nconst value: number = "text";',
		},
		{
			name: 'a TypeScript directive followed by its reason',
			code: '// @ts-expect-error the fixture passes a string on purpose\nconst count: number = "text";',
		},
		{
			name: 'a TypeScript directive whose reason follows a colon',
			code: '// @ts-ignore: the vendored typings miss this overload\nconst count: number = "text";',
		},
		{ name: 'enable directives', code: '/* oxlint-enable no-console */' },
		{
			name: 'prose that mentions a directive mid-sentence',
			code: '// Never add an oxlint-disable here; fix the rule instead.\nconst a = 1;',
		},
		{
			name: 'a generated file (header marker)',
			code: '/* eslint-disable */\n/**\n * Generated `api` utility.\n *\n * THIS CODE IS AUTOMATICALLY GENERATED.\n */\nexport const api = 1;',
		},
		{
			name: 'a generated file (@generated)',
			code: '// @generated by plugin-codegen\n// oxlint-disable-next-line no-explicit-any\nexport const x: any = 1;',
		},
	],
	invalid: [
		{
			name: 'a next-line directive without a reason',
			code: '// oxlint-disable-next-line no-control-regex\nconst re = /\\x1b/;',
			errors: [{ message: LINT }],
		},
		{
			name: 'a file-level eslint directive without a reason',
			code: '/* eslint-disable no-console */\nconsole.log(1);',
			errors: [{ message: LINT }],
		},
		{
			name: 'an empty -- reason',
			code: '// oxlint-disable-next-line no-console --   \nconsole.log(1);',
			errors: 1,
		},
		{
			name: 'a TypeScript directive without a reason',
			code: '// @ts-expect-error\nconst count: number = "text";',
			errors: [{ message: TS }],
		},
		{
			name: 'a @ts-nocheck block comment without a reason',
			code: '/* @ts-nocheck */\nexport const a = 1;',
			errors: [{ message: TS }],
		},
		{
			name: 'a comment separated from the directive by a blank line',
			code: '// Positions are stable.\n\n// oxlint-disable-next-line no-console\nconsole.log(1);',
			errors: 1,
		},
		{
			name: 'only empty comments above',
			code: '//\n/* */\n// oxlint-disable-next-line no-console\nconsole.log(1);',
			errors: 1,
		},
		{
			name: 'a trailing comment on the code line above',
			code: 'const first = 1; // the first value\nconst second = 2; // oxlint-disable-line no-unused-vars',
			errors: 1,
		},
		{
			name: 'a file that holds nothing but an unexplained directive',
			code: '/* eslint-disable no-console */',
			errors: 1,
		},
		{
			name: 'a generated marker below the first statement does not exempt the file',
			code: 'export const a = 1;\n// @generated\n\n// oxlint-disable-next-line no-console\nconsole.log(a);',
			errors: 1,
		},
	],
});
